const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { FakeFirestore } = require('./fake-firestore.cjs');
const root = process.env.ACTUAL_PROJECT_PATH || path.resolve(__dirname,'../..');
const evidence = process.env.TEST_OUTPUT_PATH || path.resolve(__dirname,'../../test-results/v43');
const { createFoodStore, loadPublishedFeed } = require(path.join(root,'functions/food-store.js'));
const { createFoodCoordinator } = require(path.join(root,'functions/food-coordinator.js'));
const { createDeviceSender } = require(path.join(root,'functions/push-provider.js'));
const passed = [];
const check = name => { passed.push(name); process.stdout.write(`PASS ${name}\n`); };
const sample = { id: 'real-001', fechaISO: '2026-10-28', empresa: 'Empresa Horizonte', horarioEvento: '08:00 AM - 05:00 PM', horarioAyB: '12:00 PM - Almuerzo', descripcionAlimentacion: 'Almuerzo ejecutivo', escenario: 'Salón 301', estado: 'Confirmado' };

async function main() {
  const core = await import(pathToFileURL(path.join(root, 'js/food-alerts-core.js')));
  assert.equal(fs.readFileSync(path.join(root, 'js/food-alerts-core.js'), 'utf8'), fs.readFileSync(path.join(root, 'functions/food-alerts-core.mjs'), 'utf8'));
  const planned = core.planFoodAlerts([sample]).alerts[0];
  assert.equal(new Date(planned.foodAt).toISOString(), '2026-10-28T17:00:00.000Z');
  assert.equal(new Date(planned.alertAt).toISOString(), '2026-10-28T16:45:00.000Z');
  assert.equal(planned.foodAt - planned.alertAt, 900000);
  assert.equal(core.localTimeToEpoch('2026-10-28', 0, 5) - 900000, Date.parse('2026-10-28T04:50:00Z'));
  for (const time of ['25:00', '12:99', '13:00 PM', '09:300', 'mañana', '']) assert.equal(core.parseFoodTimes(time).length, 0, time);
  assert.equal(core.parseFoodTimes('12:00 AM')[0].hour, 0);
  assert.equal(core.parseFoodTimes('1:15 p. m.')[0].hour, 13);
  assert.equal(core.parseFoodTimes('09:30 AM - 10:30 AM').length, 1);
  assert.equal(core.parseFoodTimes('09:30 AM / 12:00 PM, 03:30 PM').length,3);
  assert.equal(core.localTimeToEpoch('2026-02-30', 12, 0), null);
  assert.equal(core.localTimeToEpoch('2026-03-08', 2, 30, 'America/New_York'), null);
  assert.equal(core.localTimeToEpoch('2026-11-01', 1, 30, 'America/New_York'), null);
  check('Cálculo exacto a −15 minutos, America/Bogota, medianoche y rechazo de fechas/horas imposibles o ambiguas');
  for (const change of [{ estado: 'Cancelado' }, { descripcionAlimentacion: '' }, { descripcionAlimentacion: 'SIN ALIMENTACIÓN' }, { horarioAyB: '' }, { empresa: '' }, { id: '' }]) assert.equal(core.planFoodAlerts([{ ...sample, ...change }]).alerts.length, 0);
  assert.equal(core.planFoodAlerts([sample, sample]).alerts.length, 1);
  assert.equal(core.planFoodAlerts([sample,{...sample,empresa:'Otra empresa'}]).alerts.length,0);
  const multiple = core.planFoodAlerts([{ ...sample, horarioAyB: '09:00 AM\n12:00 PM', descripcionAlimentacion: 'Café\nAlmuerzo' }]).alerts;
  assert.equal(multiple.length, 2);
  assert.equal(multiple[0].description, 'Café');
  assert.equal(multiple[1].description, 'Almuerzo');
  const simultaneous=core.planFoodAlerts([{...sample,horarioAyB:'12:00 PM\n12:00 PM',descripcionAlimentacion:'Almuerzo\nBebida'}]).alerts;
  assert.equal(simultaneous.length,1);
  assert.equal(simultaneous[0].description,'Almuerzo\nBebida');
  const payload = core.foodNotification(planned);
  for (const value of ['Empresa Horizonte', 'Almuerzo ejecutivo', '12:00', 'Salón 301', 'America/Bogota']) assert(payload.body.includes(value));
  assert(!payload.body.includes('En 15 minutos'));
  const longPayload=core.foodNotification({...planned,description:'🍽️'.repeat(3000)});
  assert(longPayload.body.includes('12:00 (America/Bogota)'));
  assert(longPayload.body.length<1000);
  assert(core.isFoodAlertDue(planned, planned.alertAt));
  assert(!core.isFoodAlertDue(planned, planned.alertAt - 1));
  assert(!core.isFoodAlertDue(planned, planned.expiresAt + 1));
  check('Datos reales de empresa/servicio/salón; sin horario general de respaldo, sin alertas de cancelados o sin alimentación');

  async function engine(events = [sample], devices = [{ id: 'device-1', agendaUrl: 'https://empresa.example/agenda_movil.html' }]) {
    const database = new FakeFirestore();
    let timestamp = planned.alertAt - 3600000;
    const queued = [];
    const deleted = [];
    const sent = [];
    let behavior;
    const repository = createFoodStore(database, { documentId: () => '__name__' });
    async function publish(rows, hash) {
      await database.doc('eventos_meta/agenda_chunk_0000').set({ events: rows, dataHash: hash, chunkHash: `chunk-${hash}` });
      await database.doc('eventos_meta/publicacion').set({ count: rows.length, chunkCount: 1, dataHash: hash, chunkHashes: [`chunk-${hash}`] });
    }
    await publish(events, 'feed-1');
    const subscribers = { async *batches() { yield devices; }, async expire(id) { devices.splice(devices.findIndex(device => device.id === id), 1); } };
    const coordinator = createFoodCoordinator({ repository, queue: { async enqueue(data, options) { queued.push({ data, options }); }, async delete(id) { deleted.push(id); } }, loadFeed: () => loadPublishedFeed(database), subscribers, now: () => timestamp, sendDevice: async (device, message, options) => { if (behavior) await behavior(device, message); sent.push({ device, message, options }); return { messageId: 'provider-accepted-id' }; } });
    return { database, repository, coordinator, queued, deleted, sent, devices, publish, time: value => { timestamp = value; }, behavior: value => { behavior = value; } };
  }
  const initial = await engine();
  await Promise.all([initial.coordinator.reconcile(), initial.coordinator.reconcile()]);
  assert.equal(initial.queued.length, 1);
  assert.equal(initial.queued[0].options.scheduleTime.getTime(), planned.alertAt);
  assert.equal((await initial.coordinator.dispatch(planned.id, 1)).skipped, 'not-due');
  initial.time(planned.alertAt);
  await Promise.all([initial.coordinator.dispatch(planned.id, 1), initial.coordinator.dispatch(planned.id, 1)]);
  await initial.coordinator.dispatch(planned.id, 1);
  assert.equal(initial.sent.length, 1);
  assert.equal(initial.sent[0].options.urgency, 'high');
  assert.equal(initial.sent[0].options.ttl, 45);
  const deliveries = [...initial.database.values.entries()].filter(([name]) => name.startsWith('agenda_food_deliveries/'));
  assert.equal(deliveries.length, 1);
  assert.equal(deliveries[0][1].status, 'accepted');
  check('Repositorio transaccional y coordinador: tarea exacta, concurrencia segura, prioridad alta, registro de aceptación y una solicitud por dispositivo');
  const changed = await engine();
  await changed.coordinator.reconcile();
  await changed.publish([{ ...sample, horarioAyB: '01:00 PM' }], 'feed-2');
  await changed.coordinator.reconcile();
  assert.equal(changed.deleted.length, 1);
  changed.time(planned.alertAt);
  assert.equal((await changed.coordinator.dispatch(planned.id, 1)).skipped, 'cancelled');
  assert.equal(changed.sent.length, 0);
  for (const alteration of [{ estado: 'Cancelado' }, { descripcionAlimentacion: '' }]) {
    const cancelled = await engine();
    await cancelled.coordinator.reconcile();
    await cancelled.publish([{ ...sample, ...alteration }], 'feed-2');
    cancelled.time(planned.alertAt);
    await cancelled.coordinator.dispatch(planned.id, 1);
    assert.equal(cancelled.sent.length, 0);
  }
  const late = await engine();
  await late.coordinator.reconcile();
  late.time(planned.expiresAt + 1);
  assert.equal((await late.coordinator.dispatch(planned.id, 1)).skipped, 'expired');
  assert.equal(late.sent.length, 0);
  const reactivated = await engine();
  await reactivated.coordinator.reconcile();
  await reactivated.publish([{ ...sample, estado: 'Cancelado' }], 'feed-2');
  await reactivated.coordinator.reconcile();
  await reactivated.publish([sample], 'feed-3');
  await reactivated.coordinator.reconcile();
  assert.equal(reactivated.queued[1].data.generation, 2);
  assert.notEqual(reactivated.queued[0].options.id, reactivated.queued[1].options.id);
  reactivated.time(planned.alertAt);
  await reactivated.coordinator.dispatch(planned.id, 1);
  assert.equal(reactivated.sent.length, 0);
  await reactivated.coordinator.dispatch(planned.id, 2);
  assert.equal(reactivated.sent.length, 1);
  check('Reprogramación, cancelación, retirada de alimentación, reactivación con generación nueva y rechazo de tareas viejas o vencidas');
  const unknown = await engine();
  await unknown.coordinator.reconcile();
  unknown.time(planned.alertAt);
  unknown.behavior(async () => { throw new Error('connection lost after provider request'); });
  await unknown.coordinator.dispatch(planned.id, 1);
  unknown.behavior(null);
  await unknown.coordinator.dispatch(planned.id, 1);
  assert.equal(unknown.sent.length, 0);
  assert.equal([...unknown.database.values.entries()].find(([name]) => name.startsWith('agenda_food_deliveries/'))[1].status, 'unknown');
  const retry = await engine();
  await retry.coordinator.reconcile();
  retry.time(planned.alertAt);
  retry.behavior(async () => { throw Object.assign(new Error('quota'), { code: 'messaging/quota-exceeded' }); });
  await assert.rejects(retry.coordinator.dispatch(planned.id, 1), /retry/);
  retry.behavior(null);
  await retry.coordinator.dispatch(planned.id, 1);
  assert.equal(retry.sent.length, 1);
  const invalid = await engine();
  await invalid.coordinator.reconcile();
  invalid.time(planned.alertAt);
  invalid.behavior(async () => { throw Object.assign(new Error('removed token'), { code: 'messaging/registration-token-not-registered' }); });
  await invalid.coordinator.dispatch(planned.id, 1);
  assert.equal(invalid.devices.length, 0);
  const horizon = await engine([{ ...sample, fechaISO: '2027-12-01' }]);
  await horizon.coordinator.reconcile();
  assert.equal(horizon.queued.length, 0);
  const corrupt = await engine();
  await corrupt.database.doc('eventos_meta/agenda_chunk_0000').update({ dataHash: 'obsolete' });
  await assert.rejects(loadPublishedFeed(corrupt.database), /changed/);
  const sourceRace=await engine();
  await sourceRace.coordinator.reconcile();
  sourceRace.time(planned.alertAt);
  const originalClaim=sourceRace.repository.claimRecipient;
  sourceRace.repository.claimRecipient=async argumentsValue=>{await sourceRace.publish([{...sample,estado:'Cancelado'}],'feed-2');return originalClaim(argumentsValue);};
  await assert.rejects(sourceRace.coordinator.dispatch(planned.id,1),/retry/);
  assert.equal(sourceRace.sent.length,0);
  sourceRace.repository.claimRecipient=originalClaim;
  await sourceRace.coordinator.dispatch(planned.id,1);
  assert.equal(sourceRace.sent.length,0);
  check('Resultado desconocido sin reenvío ciego; reintento solo tras rechazo explícito; tokens inválidos retirados, horizonte de tareas y bloques obsoletos rechazados');
  const messages = [];
  const send = createDeviceSender({ messaging: { async send(message) { messages.push(message); return 'fcm-id'; } }, webPush: { async sendNotification(...args) { messages.push(args); return { statusCode: 201 }; } }, settings: { contact: 'mailto:ops@example.com', publicKey: 'public', privateKey: 'private' } });
  await send({ transport: 'fcm', fcmToken: 'registered-token' }, payload, { urgency: 'high', ttl: 45 });
  assert(!messages[0].notification);
  assert.equal(messages[0].webpush.headers.TTL, '45');
  assert.equal(messages[0].webpush.headers.Urgency, 'high');
  assert(Object.values(messages[0].data).every(value => typeof value === 'string'));
  await send({ subscription: { endpoint: 'real-subscription' } }, payload);
  assert.equal(messages[1][2].vapidDetails.privateKey, 'private');
  check('Proveedor FCM data-only sin doble visualización automática, TTL/urgencia correctos y compatibilidad Web Push con VAPID solo en backend');
  fs.mkdirSync(evidence, { recursive: true });
  fs.writeFileSync(path.join(evidence, 'pruebas-alimentacion.json'), JSON.stringify({ passed, limitations: ['Firestore, Cloud Tasks y proveedor se controlan localmente; no son pruebas de servicios desplegados ni de recepción física.'] }, null, 2));
}

main().catch(error => { console.error(error); process.exitCode = 1; });
